import { homedir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import { copyFileSync, existsSync, lstatSync, readFileSync, realpathSync, renameSync, writeFileSync } from "node:fs";
import { AGENTS } from "./agents";
import { lockEntries } from "./npx";
import { frontmatter } from "./frontmatter";
import { satlRepo } from "./config";

const H = homedir();

// read-only roots: every agent's skills folder, Claude's config (skills, commands, plugin cache), the SATL KB, scanned repos
const readRoots = () => [join(H, ".claude"), ...AGENTS.map((a) => a.dir), ...(satlRepo().path ? [join(satlRepo().path!, "knowledge-base")] : [])];

const inside = (path: string, root: string) => path === root || path.startsWith(`${root}/`);

/** Why a file can or can't be edited here. Only skills you own: plain folders, not managed by npx skills, SATL or a plugin. */
export function editability(path: string, project?: string): { editable: boolean; reason?: string } {
  const abs = resolve(path);
  const dir = dirname(abs);
  const isSkill = basename(abs) === "SKILL.md" && [join(H, ".claude/skills"), project && join(project, ".claude/skills")].some((r) => r && dirname(dir) === r);
  const isCommand = abs.endsWith(".md") && [join(H, ".claude/commands"), project && join(project, ".claude/commands")].some((r) => r && dir === r);
  if (!isSkill && !isCommand) return { editable: false, reason: "Only skills in ~/.claude/skills (or this repo's .claude/skills) can be edited here." };
  const name = isSkill ? basename(dir) : basename(abs, ".md");
  if (isSkill && lstatSync(dir).isSymbolicLink()) return { editable: false, reason: "It's a symlink to another folder; edit it at the source." };
  if (lockEntries()[name]) return { editable: false, reason: `Installed with npx skills from ${lockEntries()[name]!.source}: an update would overwrite your edits.` };
  if (name.startsWith("satl-")) return { editable: false, reason: "Generated by SATL: edit it in the knowledge base, then sync." };
  return { editable: true };
}

export function readSkillFile(path: string, project?: string) {
  const abs = resolve(path);
  if (!abs.endsWith(".md") || !existsSync(abs)) throw new Error("Not a markdown file");
  const real = realpathSync(abs); // follow symlinks, then make sure we're still somewhere we're allowed to read
  const roots = [...readRoots(), ...(project ? [join(project, ".claude")] : [])];
  if (!roots.some((r) => inside(real, r) || inside(abs, r))) throw new Error("Outside the skill folders");
  return { content: readFileSync(real, "utf8"), ...editability(abs, project) };
}

/** Save an edited SKILL.md. The previous version is kept next to it as .SKILL.md.bak (or .<name>.md.bak for commands). */
export function writeSkillFile(path: string, content: string, project?: string) {
  const abs = resolve(path);
  const check = editability(abs, project);
  if (!check.editable) throw new Error(check.reason);
  if (typeof content !== "string" || content.length > 500_000) throw new Error("Bad content");
  if (abs.endsWith("SKILL.md") && !frontmatter(content).description) throw new Error("Keep the frontmatter with a description, or Claude can't list the skill.");
  copyFileSync(abs, join(dirname(abs), `.${basename(abs)}.bak`));
  const tmp = `${abs}.${process.pid}.tmp`;
  writeFileSync(tmp, content);
  renameSync(tmp, abs);
}

/** SKILL.md straight from GitHub, to preview skills a source offers but you haven't installed. */
export async function remoteSkillFile(repo: string, folder: string) {
  if (!/^[\w.-]+\/[\w.-]+$/.test(repo) || !/^[\w./-]*$/.test(folder) || folder.includes("..")) throw new Error("Bad repo or path");
  const res = await fetch(`https://raw.githubusercontent.com/${repo}/HEAD/${folder ? `${folder}/` : ""}SKILL.md`);
  if (!res.ok) throw new Error(`GitHub ${res.status}`);
  return { content: await res.text(), editable: false, reason: "Not installed — this is the copy on GitHub." };
}
